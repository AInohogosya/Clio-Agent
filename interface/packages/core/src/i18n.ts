const tables: Record<Language, TranslationTable> = { en, ja, zh };

export type { TranslationKey };
export const translationTables = tables;

export function translate(
  language: Language,
  key: TranslationKey,
  values: Record<string, string | number> = {},
): string {
  const table = Object.prototype.hasOwnProperty.call(tables, language) ? tables[language] : en;
  const fallback = Object.prototype.hasOwnProperty.call(en, key) ? en[key] : key;
  const template = Object.prototype.hasOwnProperty.call(table, key) ? table[key] : fallback;
  return template
    .replace(/\{\{(\w+)\}\}/g, (_, name: string) => String(values[name] ?? `{{${name}}}`))
    .replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? `{${name}}`));
}

export function createTranslator(language: Language) {
  return (key: TranslationKey, values?: Record<string, string | number>) => translate(language, key, values);
}

